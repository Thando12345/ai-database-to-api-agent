// Enhanced ERD Download with Real Structure
function downloadERDDiagram() {
    try {
        const schema = currentGeneratedSchema || generateDemoSchema();
        const analysis = parseSchemaToAnalysis(schema);
        const erdSvg = generateEnhancedERDSVG(analysis);
        
        const blob = new Blob([erdSvg], { type: 'image/svg+xml' });
        const url = URL.createObjectURL(blob);
        const link = document.createElement('a');
        link.href = url;
        link.download = `erd-diagram-${currentSessionId}-${Date.now()}.svg`;
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
        URL.revokeObjectURL(url);
        
        showToast('📊 Enhanced ERD diagram with real data structure downloaded!', 'success');
    } catch (error) {
        console.error('ERD download error:', error);
        showToast('❌ ERD download failed', 'error');
    }
}

