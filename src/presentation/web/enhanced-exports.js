// Generate Enhanced Schema with Real Data
function generateEnhancedSchema(baseSchema) {
    const timestamp = new Date().toISOString();
    const sessionInfo = `-- Generated by AI Database-to-API Agent
-- Session: ${currentSessionId}
-- Generated: ${timestamp}
-- Real data structure with constraints and indexes

`;
    
    let enhanced = sessionInfo + baseSchema;
    
    // Add indexes for performance
    enhanced += "\n\n-- Performance Indexes\n";
    const tables = parseSchemaToTables(baseSchema);
    tables.forEach(table => {
        table.columns.forEach(col => {
            if (col.name.includes('_id') && !col.constraints?.includes('PRIMARY KEY')) {
                enhanced += `CREATE INDEX idx_${table.name}_${col.name} ON ${table.name}(${col.name});\n`;
            }
            if (col.name === 'email' || col.name === 'username') {
                enhanced += `CREATE INDEX idx_${table.name}_${col.name} ON ${table.name}(${col.name});\n`;
            }
        });
    });
    
    // Add sample data
    enhanced += "\n\n-- Sample Data for Testing\n";
    tables.forEach(table => {
        enhanced += generateSampleData(table);
    });
    
    return enhanced;
}

// Generate Sample Data for Tables
function generateSampleData(table) {
    let data = `\n-- Sample data for ${table.name}\n`;
    
    if (table.name === 'users' || table.name === 'customers') {
        data += `INSERT INTO ${table.name} (name, email) VALUES\n`;
        data += `  ('John Doe', 'john@example.com'),\n`;
        data += `  ('Jane Smith', 'jane@example.com'),\n`;
        data += `  ('Bob Johnson', 'bob@example.com');\n`;
    } else if (table.name === 'products') {
        data += `INSERT INTO ${table.name} (name, price, description) VALUES\n`;
        data += `  ('Laptop', 999.99, 'High-performance laptop'),\n`;
        data += `  ('Mouse', 29.99, 'Wireless optical mouse'),\n`;
        data += `  ('Keyboard', 79.99, 'Mechanical keyboard');\n`;
    } else if (table.name === 'orders') {
        data += `INSERT INTO ${table.name} (customer_id, total_amount, status) VALUES\n`;
        data += `  (1, 1109.97, 'completed'),\n`;
        data += `  (2, 29.99, 'pending'),\n`;
        data += `  (3, 79.99, 'shipped');\n`;
    } else {
        data += `-- INSERT INTO ${table.name} (column1, column2) VALUES ('value1', 'value2');\n`;
    }
    
    return data;
}